def _seq(gene: str) -> Seq:
    return Seq("".join(_CDS[gene].split()))


def _wt_protein(gene: str) -> str:
    return str(_seq(gene).translate(to_stop=False))


def _call(gene, dna_mut, aa_mut, mutation_type) -> str:
    snp = SNP(gene=gene, mrna="", dna_mut=dna_mut, aa_mut=aa_mut, mutation_type=mutation_type)
    return CancerGenomesService.get_mut_pro_seq(snp, _seq(gene))


