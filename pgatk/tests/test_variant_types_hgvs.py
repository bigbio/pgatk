class TestActionableVariantTypes:

    def test_missense_variant(self):
        """HGVS rule: single AA substitution leaves total protein length unchanged.

        Source: EZH2 c.656C>T p.S219F (missense_variant)
        DNA path: substitution at position 656 (C→T) changes codon 219 from Ser to Phe.
        """
        wt = _wt_protein("EZH2")
        result = _call("EZH2", "c.656C>T", "p.S219F", "missense_variant")

        assert result, "missense_variant must produce a non-empty protein"
        assert len(result) == len(wt), (
            f"Missense must preserve protein length: wt={len(wt)}, mut={len(result)}"
        )
        assert result[218] == "F", (
            f"Position 219 (index 218) must change to Phe; got '{result[218]}'"
        )
        assert result[:218] == wt[:218], "Residues before the substitution must be unchanged"
        assert result[219:] == wt[219:], "Residues after the substitution must be unchanged"

    def test_stop_gained(self):
        """HGVS rule: stop codon (*) introduced at the predicted position.

        Source: FCGR3B c.394A>T p.K132* (stop_gained)
        DNA path: substitution at position 394 (A→T) converts codon 132 to a stop.
        """
        result = _call("FCGR3B", "c.394A>T", "p.K132*", "stop_gained")

        assert result, "stop_gained must produce a non-empty translated sequence"
        assert result[131] == "*", (
            f"Stop codon must be introduced at position 132 (index 131); got '{result[131]}'"
        )

    def test_inframe_deletion(self):
        """HGVS rule: in-frame deletion shortens the protein by exactly the number of deleted codons.

        Source: CTNNB1 c.104_124del p.T35_G41del (inframe_deletion)
        DNA path: deletes 21 nucleotides (positions 104–124) = 7 codons = 7 amino acids.
        """
        wt = _wt_protein("CTNNB1")
        result = _call("CTNNB1", "c.104_124del", "p.T35_G41del", "inframe_deletion")

        deleted_nt = 124 - 104 + 1   # 21 nt = 7 codons
        deleted_aa = deleted_nt // 3

        assert result, "inframe_deletion must produce a non-empty protein"
        assert len(result) == len(wt) - deleted_aa, (
            f"Inframe deletion of {deleted_aa} AAs: expected len {len(wt) - deleted_aa}, "
            f"got {len(result)}"
        )
        assert result[:34] == wt[:34], "Residues before the deletion must be unchanged"

    def test_inframe_insertion_dup(self):
        """HGVS rule: in-frame duplication lengthens the protein by exactly the number of duplicated codons.

        Source: SMAP1 c.1226_1228dup p.I409dup (inframe_insertion)
        DNA path: duplicates 3 nucleotides (positions 1226–1228) = 1 codon = 1 amino acid inserted.
        """
        wt = _wt_protein("SMAP1")
        result = _call("SMAP1", "c.1226_1228dup", "p.I409dup", "inframe_insertion")

        inserted_nt = 1228 - 1226 + 1   # 3 nt = 1 codon
        inserted_aa = inserted_nt // 3

        assert result, "inframe_insertion (dup) must produce a non-empty protein"
        assert len(result) == len(wt) + inserted_aa, (
            f"Duplication of {inserted_aa} AA: expected len {len(wt) + inserted_aa}, "
            f"got {len(result)}"
        )
        assert result[:409] == wt[:409], "Residues before the duplication site must be unchanged"

    def test_protein_altering_variant(self):
        """HGVS rule: delins replaces a nucleotide range; result is non-empty and differs from WT.

        Source: NF2 c.252_262delinsCT p.L85_K88delins* (protein_altering_variant)
        DNA path: deletes positions 252–262 (11 nt) and inserts CT (2 nt).
        The AA annotation (delins*) predicts a premature stop in the altered sequence.
        """
        wt = _wt_protein("NF2")
        result = _call("NF2", "c.252_262delinsCT", "p.L85_K88delins*", "protein_altering_variant")

        assert result, "protein_altering_variant must produce a non-empty sequence"
        assert result != wt, "protein_altering_variant must differ from the wild-type sequence"

    def test_frameshift_variant(self):
        """HGVS rule: out-of-frame deletion disrupts the reading frame; the code translates the
        resulting sequence as-is (to_stop=False) producing a non-empty aberrant protein.

        Source: MEN1 c.292del p.R98Efs*21 (frameshift_variant)
        DNA path: single-nucleotide deletion at position 292 shifts the reading frame.
        """
        result = _call("MEN1", "c.292del", "p.R98Efs*21", "frameshift_variant")

        assert result, "frameshift_variant must produce a non-empty translated sequence"

    def test_start_lost(self):
        """HGVS rule: start codon destroyed; the processed sequence no longer begins with Met.

        Source: INPP4B c.3G>T p.M1? (start_lost)
        The annotation is p.M1? (ambiguous protein consequence) but dna_mut is unambiguous,
        so the DNA substitution path is taken.  ATG (Met) → ATT (Ile) at codon 1.
        """
        result = _call("INPP4B", "c.3G>T", "p.M1?", "start_lost")

        assert result, "start_lost must produce a non-empty translated sequence via the DNA path"
        assert result[0] != "M", "Start codon is destroyed; first AA must no longer be Met"
        assert result[0] == "I", "ATG→ATT encodes Ile; first AA must be Ile"

    def test_stop_lost(self):
        """HGVS rule: stop codon removed; the protein extends past the original terminus.

        Source: MYD88 c.611_613delinsGCGGCCCCC p.D204_*205delinsGGPR (protein_altering_variant,stop_lost)
        DNA path: delins at 611–613 removes the original stop codon; the protein extends.
        """
        wt = _wt_protein("MYD88")
        result = _call(
            "MYD88",
            "c.611_613delinsGCGGCCCCC",
            "p.D204_*205delinsGGPR",
            "protein_altering_variant,stop_lost",
        )

        assert result, "stop_lost must produce a non-empty protein"
        assert len(result) > len(wt), (
            f"Stop-lost protein must be longer than WT: wt={len(wt)}, mut={len(result)}"
        )

    def test_stop_retained_variant(self):
        """HGVS rule: synonymous change at the stop codon; stop is preserved; length unchanged.

        Source: EPHA3 c.2756G>A p.*919= (stop_retained_variant)
        DNA path: TGA (stop) → TAA (stop); both are stop codons, protein length is unchanged.
        """
        wt = _wt_protein("EPHA3")
        result = _call("EPHA3", "c.2756G>A", "p.*919=", "stop_retained_variant")

        assert result, "stop_retained_variant must produce a non-empty sequence"
        assert len(result) == len(wt), (
            f"Stop-retained must preserve protein length: wt={len(wt)}, mut={len(result)}"
        )
        assert result[-1] == "*", "Stop codon must still be present at the terminus"


